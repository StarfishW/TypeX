export type MessageKey = keyof typeof en

type PluralCategory = 'zero' | 'one' | 'two' | 'few' | 'many' | 'other'

/** A translation: any subset of the English keys, plus plural forms English does not use (such as `.few`). */
export type Messages = { readonly [K in MessageKey]?: string } & {
  readonly [K: `${string}.${PluralCategory}`]: string | undefined
}
